from typing import Any


def _block(ref: str, kind: str, text: str, order: int, parent: str | None = None) -> dict[str, Any]:
    return {"id": ref, "parentBlockId": parent, "type": kind, "orderIndex": order, "title": None,
            "content": {"text": text}, "styleConfig": {"level": 1} if kind == "HEADER" else None, "dataConfig": None}


def _todo(ref: str, text: str, checked: bool, order: int, parent: str | None = None) -> dict[str, Any]:
    return {**_block(ref, "TODO", text, order, parent), "content": {"text": text, "checked": checked}}


def _view(ref: str, order: int) -> dict[str, Any]:
    return {**_block(ref, "DATABASE_VIEW", "", order), "content": None}


def _property(ref: str, name: str, kind: str, position: str, options: list[tuple[str, str]] | None = None) -> dict[str, Any]:
    return {"id": ref, "name": name, "type": kind, "position": position, "isDefault": kind == "TITLE",
            "isHideable": kind != "TITLE",
            "options": [{"id": oid, "name": label, "color": None, "position": str(index)}
                        for index, (oid, label) in enumerate(options or [])]}


def _database(ref: str, page_id: str, name: str, properties: list[dict[str, Any]],
              rows: list[dict[str, Any]]) -> dict[str, Any]:
    return {"id": ref, "pageId": page_id, "name": name, "properties": properties,
            "views": [{"id": f"v-{ref}", "databaseId": ref, "name": "Bảng", "type": "TABLE", "position": "0",
                       "properties": [{"propertyId": prop["id"], "position": str(index), "visible": True, "width": None}
                                      for index, prop in enumerate(properties)]}],
            "rows": [{**row, "databaseId": ref} for row in rows]}


def _context(page_id: str, title: str, blocks: list[dict[str, Any]],
             databases: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    databases = databases or []
    references = [{"blockId": block["id"], "databaseId": databases[0]["id"], "viewId": f"v-{databases[0]['id']}"}
                  for block in blocks if block["type"] == "DATABASE_VIEW"] if databases else []
    return {
        "schemaVersion": 1, "builtAt": "2026-11-14T08:00:00.000Z",
        "page": {"id": page_id, "workspaceId": "ws-dev2", "teamspaceId": None, "parentPageId": None, "title": title,
                 "icon": None, "coverUrl": None, "updatedAt": "2026-11-14T07:30:00.000Z"},
        "blocks": blocks, "databaseReferences": references, "databases": databases,
        "completeness": {
            "blocks": {"total": len(blocks), "included": len(blocks), "truncated": False},
            "databases": {"total": len(databases), "included": len(databases), "truncated": False},
            "rows": [{"databaseId": db["id"], "total": len(db["rows"]), "included": len(db["rows"]),
                      "truncated": False, "selection": "BOUNDED"} for db in databases],
            "textTruncated": False,
        },
    }


def _row(ref: str, name: str, status: str | None, owner: str | None = None, due: str | None = None) -> dict[str, Any]:
    return {"id": ref, "values": {"d-name": name, "d-status": status, "d-owner": owner,
                                  "d-due": {"start": due} if due else None}}


